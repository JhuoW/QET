"""Acceptance tests: the real implementation (src/qet) must reproduce the golden fixtures.

The tests reach the implementation only through the thin facade `qet.core.api` described in
docs/SPEC.md §10, so internal data structures are free. Do not edit this file or the fixtures;
if you believe one is wrong, stop and write it up as an open question in docs/DECISIONS.md.
"""
import json
import math
import re
from pathlib import Path

import pytest

FIX = Path(__file__).resolve().parents[1] / "fixtures"
ROOT = Path(__file__).resolve().parents[2]


def load(name):
    return json.loads((FIX / name).read_text(encoding="utf-8"))


CANON, COMPILE, REDUCE, RENDER = load("canonical.json"), load("compile.json"), load("reduce.json"), load("render.json")
LATTICE = load("lattice.json")


class _Missing:
    """Stands in for the facade until it exists, so every test fails (rather than errors) with one clear reason."""

    def __init__(self, exc):
        self.exc = exc

    def __getattr__(self, name):
        raise AssertionError(f"qet.core.api is not importable ({self.exc!r}); implement docs/SPEC.md §10")


@pytest.fixture(scope="module")
def api():
    try:
        from qet.core import api as mod
    except Exception as exc:  # noqa: BLE001
        return _Missing(exc)
    return mod


def close(a, b):
    return a == b or math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-12)


def assert_map_close(got, expected, what):
    got = {} if got is None else got
    for k, v in expected.items():
        assert close(got.get(k, 0.0), v), f"{what}[{k!r}]: got {got.get(k)!r}, expected {v!r}"
    extra = {k: v for k, v in got.items() if k not in expected and v != 0.0}
    assert not extra, f"{what}: unexpected non-zero entries {extra}"


