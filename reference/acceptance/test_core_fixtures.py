# ----------------------------------------------------------------------------- §5 reduce + render
@pytest.mark.parametrize("case", REDUCE["cases"], ids=lambda c: c["name"])
def test_reduce(api, case):
    H = api.reduce(case["history"], case["contracts"])
    assert [e["name"] for e in H] == case["expected_names"]
    if "expected_obs" in case:
        assert [e["obs"] for e in H] == case["expected_obs"]


def test_reduce_is_invariant_over_all_legal_orders(api):
    spec = REDUCE["seven_step_legal_orders"]
    for order in spec["orders"]:
        H = api.reduce([spec["steps"][i] for i in order], spec["contracts"])
        assert [e["name"] for e in H] == spec["expected_names"], order


@pytest.mark.parametrize("case", RENDER["cases"], ids=lambda c: c["name"])
def test_render(api, case):
    task = case.get("task", RENDER["task"])
    contracts = case.get("contracts", RENDER["contracts"])
    got = api.render(task, case["history"], contracts, variant=case["variant"], truncation=case.get("truncation"))
    assert got["system"] == case["expected"]["system"]
    assert got["user"] == case["expected"]["user"]


def test_same_completed_set_same_bytes(api):
    by_name = {c["name"]: c for c in RENDER["cases"]}
    for group in RENDER["same_prompt_groups"]:
        outs = [api.render(RENDER["task"], by_name[n]["history"], RENDER["contracts"], variant="quotient") for n in group]
        assert all(o == outs[0] for o in outs), group


# ----------------------------------------------------------------------------- §6, §8 lattice and weights
RUNS = [(c, i) for c in LATTICE["cases"] for i in range(len(c["runs"]))]


@pytest.mark.parametrize("case,i", RUNS, ids=lambda x: x["name"] if isinstance(x, dict) else str(x))
def test_lattice_summary(api, case, i):
    run = case["runs"][i]
    got = api.lattice_summary(n=case["n"], preds=case["preds"], logp=case["logp"], method=run["method"],
                              lam=run["lam"], order=run.get("order"), paths=run.get("paths"),
                              states=run.get("states"), plus=run.get("plus", False))
    exp = run["expected"]
    label = f"{case['name']}/{run['method']}/lam={run['lam']}"
    assert_map_close(got["logB"], exp["logB"], f"{label} logB")
    assert_map_close(got["mu"], exp["mu"], f"{label} mu")
    assert_map_close(got["weights"], exp["weights"], f"{label} weights")
    for key in ("qet_objective", "surrogate", "objective"):
        assert close(got[key], exp[key]), f"{label} {key}: got {got[key]!r}, expected {exp[key]!r}"
    if exp["logB_plus"] is not None:
        assert_map_close(got["logB_plus"], exp["logB_plus"], f"{label} logB_plus")


# ----------------------------------------------------------------------------- hygiene
def test_src_does_not_import_the_oracle():
    src = ROOT / "src" / "qet"
    assert src.is_dir(), "src/qet does not exist yet"
    bad = re.compile(r"qet_ref|from\s+reference\b|import\s+reference\b|['\"]reference['\"]")
    hits = [str(p.relative_to(ROOT)) for p in src.rglob("*.py") if bad.search(p.read_text(encoding="utf-8"))]
    assert not hits, f"production code must not use the reference oracle: {hits}"
